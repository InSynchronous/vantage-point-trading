export function getNodeDef(type: string): NodeDef {
  const d = NODE_DEFS.find((n) => n.type === type);
  if (!d) throw new Error(`Unknown node type ${type}`);
  return d;
}

export function defaultConfig(def: NodeDef): Record<string, unknown> {
  const cfg: Record<string, unknown> = {};
  for (const f of def.fields) cfg[f.key] = f.default;
  return { ...cfg, ...def.defaults };
}
